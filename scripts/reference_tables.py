#!/usr/bin/env python3
"""Generate docs/reference-tables.md from data/ — the worked numbers the app must reproduce.

Run from the repo root:  python3 scripts/reference_tables.py
Same formulas as SPEC §6; the TypeScript lib/optics.ts must match these outputs.
"""
import json, glob, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAMBDA_UM = 0.55
AIRY = 2.44 * LAMBDA_UM  # µm per f-number
THIRDS = [1.4, 1.6, 1.8, 2, 2.2, 2.5, 2.8, 3.2, 3.5, 4, 4.5, 5, 5.6, 6.3, 7.1, 8, 9, 10, 11,
          13, 14, 16, 18, 20, 22, 25, 29, 32, 36, 40, 45, 51, 57, 64]
DX = {"width_mm": 23.5, "height_mm": 15.7}


def snap(n):
    return min(THIRDS, key=lambda t: abs(math.log2(t) - math.log2(n)))


def fs(n):
    s = snap(n)
    return f"f/{s:g}"


def load(pattern):
    out = {}
    for f in sorted(glob.glob(os.path.join(ROOT, pattern))):
        d = json.load(open(f))
        out[d["id"]] = d
    return out


def pitch(body):
    s = body["sensor"]
    return s["width_mm"] / s["width_px"] * 1000


def diag(w, h):
    return math.hypot(w, h)


def bands(p_um, w_mm, h_mm):
    c_out_um = diag(w_mm, h_mm) / 3000 * 1000
    return {
        "measurable": 2 * p_um / AIRY,
        "visible_100": 2.5 * p_um / AIRY,
        "large_output": c_out_um / AIRY,
    }


def dof_mm(N, m, c_mm, P=1.0):
    return 2 * N * c_mm * (1 + m / P) / (m * m)


def main():
    kit = json.load(open(os.path.join(ROOT, "data", "kit.json")))
    allb = load("data/bodies/*.json")
    bodies = {b["id"]: allb[b["id"]] for b in sorted(kit["bodies"], key=lambda x: x["order"]) if b["id"] in allb}
    alll = load("data/lenses/*.json")
    order = [l for g in kit["lens_groups"] for l in g["lenses"]]
    lenses = {i: alll[i] for i in order if i in alll}
    L = ["# Reference tables (generated)", "",
         "Generated by `scripts/reference_tables.py` from `data/`. Formulas: SPEC §6. "
         "λ = 0.55 µm; Airy diameter d = 2.44·λ·N. Bands: measurable d ≥ 2p, visible at 100% d ≥ 2.5p, "
         "large output d ≥ diagonal/3000. Apertures snapped to third stops; exact values in brackets.", ""]

    L += ["## Diffraction bands per body", "",
          "| Body | Mode | Pixel pitch | Measurable | Visible at 100% | Large output |",
          "|---|---|---|---|---|---|"]
    for bid, b in bodies.items():
        s = b["sensor"]; p = pitch(b)
        for mode, (w, h) in [("native", (s["width_mm"], s["height_mm"]))] + (
                [("DX crop", (DX["width_mm"], DX["height_mm"]))] if b.get("format") == "FX" else []):
            bd = bands(p, w, h)
            L.append(f"| {b['name']} | {mode} | {p:.2f} µm | {fs(bd['measurable'])} ({bd['measurable']:.1f}) | "
                     f"{fs(bd['visible_100'])} ({bd['visible_100']:.1f}) | {fs(bd['large_output'])} ({bd['large_output']:.1f}) |")
    L.append("")

    L += ["## Close-up per lens × body", "",
          "Frame = smallest subject that fills the frame at maximum magnification. DOF at max magnification uses "
          "c = 2p (100% view) and P = 1. For lenses where the camera displays the effective aperture (Z MC 105), "
          "N below is the displayed number; for others it is the set number and N_eff = N(1+m).", ""]
    for lid, d in lenses.items():
        mags = d["close_focus"].get("max_mag") or []
        if not mags or mags[0].get("value") is None:
            continue
        mm = max(mags, key=lambda x: x["value"] or 0)
        m = mm["value"]
        displays_eff = d["close_focus"].get("camera_displays_effective") is True  # null = unverified -> treat as nominal
        L += [f"### {d['name']}", "",
              f"Max magnification {m:g}× (1:{1/m:.1f}) at {mm['focal_mm']} mm. "
              f"Sweet spot: {d['quick'].get('sweet_spot')}. Close-up best: {d['quick'].get('close_up_best')}. "
              f"Camera displays effective aperture: {'yes' if displays_eff else 'no / unverified'}.", "",
              "| Body | Frame at max mag | N_eff at set f/5.6 · f/8 · f/11 | DOF @100% f/5.6 · f/8 · f/11 |",
              "|---|---|---|---|"]
        for bid, b in bodies.items():
            s = b["sensor"]; p = pitch(b)
            w, h = (DX["width_mm"], DX["height_mm"]) if (d.get("coverage") == "DX" and b.get("format") == "FX") else (s["width_mm"], s["height_mm"])
            frame = f"{w/m:.0f} × {h/m:.0f} mm"
            c = 2 * p / 1000
            neffs, dofs = [], []
            for N in (5.6, 8, 11):
                if displays_eff:
                    neff = N
                    dofv = 2 * N * c / (m * m)  # N already includes (1+m)
                else:
                    neff = N * (1 + m)
                    dofv = dof_mm(N, m, c)
                neffs.append(f"f/{neff:.1f}")
                dofs.append(f"{dofv:.2f} mm" if dofv < 10 else f"{dofv/10:.1f} cm")
            L.append(f"| {b['name']} | {frame} | {' · '.join(neffs)} | {' · '.join(dofs)} |")
        L.append("")

    out = os.path.join(ROOT, "docs", "reference-tables.md")
    open(out, "w").write("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
